import itertools
import typing
from collections.abc import Callable, Iterable

import click

from clickify.func import FuncInfo, ParamInfo
from clickify.handler.base import (
    BaseParamHandler,
    FailedHandlerException,
    HandlerResult,
    IgnoreParameterException,
    NotHandledException,
)

if typing.TYPE_CHECKING:
    from clickify.registry import HandlerRegistry


class FunctionHandler[T](BaseParamHandler):
    """Provide args derived from a function signature, then call the function with them to construct result.

    Any annotations provided by click (or passed in as override_params) will take precedence over the function
    signature.
    Note: This may also add parameters not present in the function (Eg. with an exiting callback)
    """

    def __init__(
        self,
        registry: HandlerRegistry,
        func: Callable[..., T],
        override_params: list[click.Parameter] | None = None,
        allow_extra_params: bool = False,
    ) -> None:
        """Wrap the args of a function as a handler for some returned type.

        Arguments:
            registry:
                Used to lookup handlers for the function arg types
            func:
                The function to handle.
                All args will be converted to handlers
            override_params:
                Any arguments that should be overridden by click parameters
                (Used for decotator / directly passed params)
            allow_extra_params:
                Allow passing through any extra parameters this handler gets to
                the function.
                May be needed for top-level functions where extra parameters may
                be passed through options added post-creation etc.


        """
        self.registry = registry
        self.funcinfo = FuncInfo.from_func(func)
        self.allow_extra_params = allow_extra_params

        # Get click decorator annotations:

        if override_params is None:
            override_params = []

        decorator_params = getattr(func, "__click_params__", [])
        if decorator_params:
            override_params += reversed(decorator_params)
            del func.__click_params__  # type: ignore

        self.override_params = override_params
        # Store names to ignore in signature to prevent adding twice
        self.override_param_names = set(p.name for p in self.override_params)

    def _get_params(self) -> Iterable[HandlerResult[typing.Any]]:
        for info in self.funcinfo.params:
            if info.name not in self.override_param_names:
                try:
                    yield self.registry.handle_param(info)
                except IgnoreParameterException:
                    pass

        # Include click provided params (passed as arg or from @option annotations)
        for param in self.override_params:
            # Make param from this.
            info = ParamInfo.from_click_param(param)
            yield HandlerResult(info, [param])

    def __call__(self, info: ParamInfo) -> HandlerResult[typing.Any] | None:
        """We ignore paraminfo, and create a new set of parameters here."""

        # TODO: Maybe prefix param names with a prefix from info.name?
        #  - would still be conflicts from decls, unless leave all autogenerated from name.

        try:
            # TODO: allow prefixing opts with paraminfo argname?
            handler_results = list(self._get_params())
        except NotHandledException as ex:
            # If one of the types we're registered as fails, we want to report the error, rather
            # than just say we don't handle the top-level type.
            raise FailedHandlerException(f"A subparameter for handler function was not registered: {ex}") from ex

        def callback(opts: dict[str, typing.Any]) -> T:
            resolved_params: dict[str, typing.Any] = {}
            for h in handler_results:
                try:
                    resolved_params[h.paraminfo.name] = h.callback_internal(opts)
                except IgnoreParameterException:
                    # Ignore manually added expose_value=False params with no
                    # corresponding value passed to function.
                    pass

            if self.allow_extra_params:
                # Any options not handled by a handler are just passed through unchanged.
                # This can happen from stuff like a click.option() applied after the
                # command decorator was applied, or other post-creation modifications.
                # Should not be used for registered type handlers etc, as could result in
                # then receiving params intended for other handlers
                resolved_params = opts | resolved_params

            return self.funcinfo.invoke(**resolved_params)

        params = list(itertools.chain.from_iterable(h.params for h in handler_results))

        return HandlerResult(info, params, callback)
